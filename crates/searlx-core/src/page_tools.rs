/// A DOM text node or attribute candidate for in-place translation (`FEATURES.md` §5.3).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct TranslatableNode {
    /// Stable node identifier within the document/frame.
    pub node_id: String,
    /// Tag name of the owning element.
    pub tag: String,
    /// Whether the element or an ancestor has `translate="no"`, `.notranslate`, or `contenteditable`.
    pub excluded: bool,
    /// Original text (including `[1]`, `[2]` inline child markers).
    pub text: String,
}

impl TranslatableNode {
    /// Whether this node is eligible for translation (`FEATURES.md` §5.3: skips
    /// `code`, `pre`, `script`, `style`, `input`, `textarea`, editable areas,
    /// `translate="no"`, `.notranslate`).
    #[must_use]
    pub fn is_eligible(&self) -> bool {
        if self.excluded || self.text.trim().is_empty() {
            return false;
        }
        !matches!(
            self.tag.to_ascii_lowercase().as_str(),
            "code" | "pre" | "script" | "style" | "kbd" | "samp" | "var" | "textarea"
        )
    }
}

/// In-place translation session that translates without adding/removing DOM
/// elements and restores exact original text on `Show Original` (`FEATURES.md` §5.3, P2-11).
#[derive(Clone, Debug, Default)]
pub struct TranslationManager {
    /// Target language code (e.g. `"en"`).
    pub target_language: String,
    /// Sites configured to always translate (never written from private tabs).
    always_translate_sites: BTreeSet<String>,
    /// Original text per `node_id` for exact restoration on `Show Original`.
    originals: BTreeMap<String, String>,
    /// Currently displayed text per `node_id`.
    current_texts: BTreeMap<String, String>,
    /// Whether the page is currently showing translated text.
    pub is_translated: bool,
}

impl TranslationManager {
    /// Create a translation manager targeting `target_language`.
    #[must_use]
    pub fn new(target_language: impl Into<String>) -> Self {
        Self {
            target_language: target_language.into(),
            ..Self::default()
        }
    }

    /// Mark a site to always translate; ignored in private tabs (`FEATURES.md` §5.3).
    pub fn set_always_translate(&mut self, site_host: &str, enabled: bool, private: bool) {
        if private {
            return;
        }
        let site = normalize_site_key(site_host);
        if enabled {
            self.always_translate_sites.insert(site);
        } else {
            self.always_translate_sites.remove(&site);
        }
    }

    /// Whether `site_host` is in the `translate.always` list.
    #[must_use]
    pub fn should_always_translate(&self, site_host: &str) -> bool {
        self.always_translate_sites
            .contains(&normalize_site_key(site_host))
    }

    /// Translate eligible nodes in place using `translator`, deduplicating
    /// repeated strings and preserving inline `[1]`, `[2]` markers (`FEATURES.md` §5.3).
    pub fn translate_in_place<F>(&mut self, nodes: &[TranslatableNode], mut translator: F) -> usize
    where
        F: FnMut(&str, &str) -> String,
    {
        let mut cache: BTreeMap<String, String> = BTreeMap::new();
        let mut translated_count = 0_usize;

        for node in nodes {
            self.originals
                .entry(node.node_id.clone())
                .or_insert_with(|| node.text.clone());

            if !node.is_eligible() {
                self.current_texts
                    .insert(node.node_id.clone(), node.text.clone());
                continue;
            }

            let translated = cache
                .entry(node.text.clone())
                .or_insert_with(|| translator(&node.text, &self.target_language))
                .clone();
            self.current_texts.insert(node.node_id.clone(), translated);
            translated_count += 1;
        }
        self.is_translated = translated_count > 0;
        translated_count
    }

    /// Current text for `node_id`.
    #[must_use]
    pub fn text_for(&self, node_id: &str) -> Option<&str> {
        self.current_texts.get(node_id).map(String::as_str)
    }

    /// Restore every node to its exact pre-translation text (`Show Original`, `FEATURES.md` §5.3).
    pub fn show_original(&mut self) {
        for (id, orig) in &self.originals {
            self.current_texts.insert(id.clone(), orig.clone());
        }
        self.is_translated = false;
    }
}

