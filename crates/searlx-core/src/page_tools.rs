/// Maximum height in points for a page capture (`30,000 pt`, `FEATURES.md` §5.4).
pub const CAPTURE_MAX_HEIGHT_PT: f64 = 30_000.0;
/// Maximum total pixels for a capture (`64,000,000` ≈ 256 MB RGBA, `FEATURES.md` §5.4).
pub const CAPTURE_MAX_PIXELS: u64 = 64_000_000;
/// Minimum capture dimension in points (`2×2 pt`, `FEATURES.md` §5.4).
pub const CAPTURE_MIN_PT: f64 = 2.0;

/// What part of the page to capture (`FEATURES.md` §5.4).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub enum CaptureRequest {
    /// Dragged rectangular area in CSS pixels (`x, y, width, height`).
    Area {
        x: f64,
        y: f64,
        width: f64,
        height: f64,
    },
    /// Clicked DOM element with its outline label (`<tag> W×H`).
    Element {
        tag: String,
        x: f64,
        y: f64,
        width: f64,
        height: f64,
    },
    /// Whole page (`width, height` in page points).
    WholePage { width: f64, height: f64 },
}

/// Planned capture operation ready for the engine and clipboard (`P2-12`).
#[derive(Clone, Debug, PartialEq)]
pub struct CapturePlan {
    /// Whether the capture overlay must be hidden before drawing (`always true`, `FEATURES.md` §5.4).
    pub remove_overlay_before_draw: bool,
    /// Whether to use `createPDF` + first-page rasterization (used for `WholePage`
    /// to avoid WebKit's white off-screen strip on long pages, `FEATURES.md` §5.4).
    pub use_pdf_rasterization: bool,
    /// Target capture width in view points (cropped/clamped).
    pub view_width_pt: f64,
    /// Target capture height in view points (cropped to `<= 30,000 pt`).
    pub view_height_pt: f64,
    /// Output pixel width after applying display scale and the 64M-pixel cap.
    pub output_width_px: u32,
    /// Output pixel height after applying display scale and the 64M-pixel cap.
    pub output_height_px: u32,
    /// Optional element outline label (`"article · 720×480"`).
    pub element_outline_label: Option<String>,
    /// File name in Downloads (`Capture YYYY-MM-DD at HH.MM.SS.png`, never the site name!).
    pub download_file_name: String,
    /// Whether the clipboard item must be marked local-only (`currentHostOnly`).
    pub clipboard_local_only: bool,
    /// Whether the clipboard item must be marked transient (`org.nspasteboard.TransientType` for private tabs).
    pub clipboard_transient: bool,
}

/// Compute a validated [`CapturePlan`] applying all `FEATURES.md` §5.4 limits and privacy rules.
#[must_use]
pub fn plan_page_capture(
    request: &CaptureRequest,
    pinch_zoom: f64,
    display_scale: f64,
    date_ymd: &str,
    time_hms: &str,
    private_tab: bool,
) -> CapturePlan {
    let zoom = if pinch_zoom.is_finite() && pinch_zoom > 0.0 {
        pinch_zoom
    } else {
        1.0
    };
    let scale = if display_scale.is_finite() && display_scale >= 1.0 {
        display_scale
    } else {
        1.0
    };

    let (raw_w, raw_h, use_pdf, outline_label) = match request {
        CaptureRequest::Area { width, height, .. } => {
            // Area converts CSS pixels to view points using pinch zoom (`FEATURES.md` §5.4).
            (width * zoom, height * zoom, false, None)
        }
        CaptureRequest::Element {
            tag, width, height, ..
        } => {
            let label = format!(
                "{} · {}×{}",
                tag,
                width.round() as i64,
                height.round() as i64
            );
            (width * zoom, height * zoom, false, Some(label))
        }
        CaptureRequest::WholePage { width, height } => {
            // Whole-page shots ignore pinch zoom and use PDF rasterization (`FEATURES.md` §5.4).
            (*width, *height, true, None)
        }
    };

    let view_width_pt = raw_w.max(CAPTURE_MIN_PT);
    let view_height_pt = raw_h.clamp(CAPTURE_MIN_PT, CAPTURE_MAX_HEIGHT_PT);

    let mut px_w = (view_width_pt * scale).round().max(2.0);
    let mut px_h = (view_height_pt * scale).round().max(2.0);
    let total_pixels = px_w * px_h;
    if total_pixels > (CAPTURE_MAX_PIXELS as f64) {
        let downscale = ((CAPTURE_MAX_PIXELS as f64) / total_pixels).sqrt();
        px_w = (px_w * downscale).floor().max(2.0);
        px_h = (px_h * downscale).floor().max(2.0);
    }

    CapturePlan {
        remove_overlay_before_draw: true,
        use_pdf_rasterization: use_pdf,
        view_width_pt,
        view_height_pt,
        output_width_px: px_w as u32,
        output_height_px: px_h as u32,
        element_outline_label: outline_label,
        download_file_name: format!("Capture {date_ymd} at {time_hms}.png"),
        clipboard_local_only: true,
        clipboard_transient: private_tab,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dusk_darkens_light_pages_leaves_dark_sites_untouched_and_falls_back_on_budget() {
        let mut dusk = DuskController::new(true);
        let mut budget = DuskBudget::default();

        // Dark site (RGB 20, 20, 24) is untouched.
        let dark_decision = dusk.evaluate_page(
            "dark.example.com",
            true,
            (20, 20, 24),
            false,
            &["body { background: #111; color: #eee; }"],
            &mut budget,
            false,
        );
        assert_eq!(dark_decision, DuskDecision::Untouched);

        // Light site (RGB 250, 250, 250) generates dark twins and leaves img/video filter:none.
        let light_decision = dusk.evaluate_page(
            "light.example.com",
            true,
            (250, 250, 250),
            false,
            &["body { background: #ffffff; color: #000000; }"],
            &mut budget,
            false,
        );
        let DuskDecision::DarkTwins { css } = light_decision else {
            panic!("expected dark twins");
        };
        assert!(css.contains("oklch("));
        assert!(css.contains("img, picture, video, canvas { filter: none !important; }"));

        // Private tab toggle does not leak into durable preferences.
        dusk.toggle_site("private.example.com", true, true);
        assert!(
            !dusk
                .durable_site_preferences()
                .contains_key("private.example.com")
        );

        // Exceeding the 2,000-sheet budget gives up cleanly onto the filter fallback.
        budget.sheets_processed = DUSK_MAX_SHEETS;
        let fallback = dusk.evaluate_page(
            "light.example.com",
            true,
            (250, 250, 250),
            false,
            &["body { background: #fff; }"],
            &mut budget,
            false,
        );
        assert_eq!(
            fallback,
            DuskDecision::FilterFallback {
                css: DUSK_FILTER_FALLBACK_CSS
            }
        );
    }

    #[test]
    fn translates_french_article_in_place_skips_code_and_restores_exact_original() {
        let nodes = vec![
            TranslatableNode {
                node_id: "n1".into(),
                tag: "h1".into(),
                excluded: false,
                text: "Bonjour le monde".into(),
            },
            TranslatableNode {
                node_id: "n2".into(),
                tag: "p".into(),
                excluded: false,
                text: "Cliquez sur [1] pour continuer.".into(),
            },
            TranslatableNode {
                node_id: "n3".into(),
                tag: "code".into(),
                excluded: false,
                text: "let bonjour = 42;".into(),
            },
            TranslatableNode {
                node_id: "n4".into(),
                tag: "span".into(),
                excluded: true, // .notranslate
                text: "Ne pas traduire".into(),
            },
        ];

        let mut mgr = TranslationManager::new("en");
        let count = mgr.translate_in_place(&nodes, |text, _lang| match text {
            "Bonjour le monde" => "Hello world".into(),
            "Cliquez sur [1] pour continuer." => "Click on [1] to continue.".into(),
            other => other.to_owned(),
        });

        assert_eq!(count, 2);
        assert!(mgr.is_translated);
        assert_eq!(mgr.text_for("n1"), Some("Hello world"));
        assert_eq!(mgr.text_for("n2"), Some("Click on [1] to continue."));
        assert_eq!(mgr.text_for("n3"), Some("let bonjour = 42;"));
        assert_eq!(mgr.text_for("n4"), Some("Ne pas traduire"));

        // Show Original restores exact original French strings.
        mgr.show_original();
        assert!(!mgr.is_translated);
        assert_eq!(mgr.text_for("n1"), Some("Bonjour le monde"));
        assert_eq!(mgr.text_for("n2"), Some("Cliquez sur [1] pour continuer."));
    }

    #[test]
    fn twenty_thousand_pt_page_captures_via_pdf_and_outlines_element() {
        let whole = plan_page_capture(
            &CaptureRequest::WholePage {
                width: 1280.0,
                height: 20_000.0,
            },
            1.5, // pinch zoom ignored on whole-page capture
            2.0, // 2x Retina
            "2026-11-21",
            "09.45.00",
            true,
        );
        assert!(whole.remove_overlay_before_draw);
        assert!(whole.use_pdf_rasterization);
        assert_eq!(whole.view_height_pt, 20_000.0);
        assert!(
            (u64::from(whole.output_width_px) * u64::from(whole.output_height_px))
                <= CAPTURE_MAX_PIXELS
        );
        assert_eq!(
            whole.download_file_name,
            "Capture 2026-11-21 at 09.45.00.png"
        );
        assert!(whole.clipboard_local_only);
        assert!(whole.clipboard_transient);

        let elem = plan_page_capture(
            &CaptureRequest::Element {
                tag: "article".into(),
                x: 10.0,
                y: 20.0,
                width: 720.0,
                height: 480.0,
            },
            1.0,
            1.0,
            "2026-11-21",
            "09.45.01",
            false,
        );
        assert!(!elem.use_pdf_rasterization);
        assert_eq!(
            elem.element_outline_label.as_deref(),
            Some("article · 720×480")
        );
        assert!(!elem.clipboard_transient);
    }
}
