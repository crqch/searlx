/// Maximum stylesheets processed by Dusk before falling back to root filter (`FEATURES.md` §5.7).
pub const DUSK_MAX_SHEETS: usize = 2_000;
/// Maximum held characters in Dusk twin sheets (`FEATURES.md` §5.7).
pub const DUSK_MAX_HELD_CHARS: usize = 8_000_000;
/// Maximum cumulative characters generated by Dusk (`FEATURES.md` §5.7).
pub const DUSK_MAX_MADE_CHARS: usize = 48_000_000;

/// Root CSS filter fallback when dark twins are not ready or budget is exceeded.
/// Reverses `img`, `picture`, `video`, `canvas`, and `iframe` so photos and
/// videos are never inverted (`FEATURES.md` §5.7).
pub const DUSK_FILTER_FALLBACK_CSS: &str = "html { filter: invert(1) hue-rotate(180deg) contrast(.85) !important; }\n\
img, picture, video, canvas, iframe { filter: invert(1) hue-rotate(180deg) !important; }";

/// Budget tracker for Dusk dark-twin stylesheet synthesis (`FEATURES.md` §5.7).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct DuskBudget {
    /// Number of stylesheets processed so far.
    pub sheets_processed: usize,
    /// Currently held twin characters.
    pub held_chars: usize,
    /// Total cumulative twin characters created.
    pub made_chars: usize,
    /// True once any budget ceiling was exceeded.
    pub exhausted: bool,
}

impl DuskBudget {
    /// Record a processed stylesheet of `sheet_len` characters; returns `false`
    /// and sets `exhausted = true` if any budget limit is exceeded (`FEATURES.md` §5.7).
    pub fn record_sheet(&mut self, sheet_len: usize) -> bool {
        if self.exhausted {
            return false;
        }
        self.sheets_processed = self.sheets_processed.saturating_add(1);
        self.held_chars = self.held_chars.saturating_add(sheet_len);
        self.made_chars = self.made_chars.saturating_add(sheet_len);
        if self.sheets_processed > DUSK_MAX_SHEETS
            || self.held_chars > DUSK_MAX_HELD_CHARS
            || self.made_chars > DUSK_MAX_MADE_CHARS
        {
            self.exhausted = true;
            return false;
        }
        true
    }
}

/// Output of evaluating Dusk darkening for a page (`P2-10`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum DuskDecision {
    /// Page is already dark, frame is light, Dusk is paused, or fullscreen disabled the filter.
    Untouched,
    /// Dark twin stylesheet generated without touching images/photos.
    DarkTwins {
        /// Synthesized dark-twin CSS rules.
        css: String,
    },
    /// Budget exceeded or fallback requested; uses root invert filter while protecting images/video.
    FilterFallback {
        /// Filter fallback CSS.
        css: &'static str,
    },
}

/// Measure whether a 48×48 snapshot average RGB color belongs to a light page (`FEATURES.md` §5.7).
#[must_use]
pub fn is_measured_light_page(r: u8, g: u8, b: u8) -> bool {
    let luminance = 0.2126 * f64::from(r) + 0.7152 * f64::from(g) + 0.0722 * f64::from(b);
    luminance >= 140.0
}

/// Dusk controller managing per-site toggles (`⇧⌘D`), session pause (`⌥⇧⌘D`),
/// and private-tab memory-only overrides (`FEATURES.md` §5.7, P2-10).
#[derive(Clone, Debug, Default)]
pub struct DuskController {
    /// Whether `pages.dusk` is enabled globally.
    pub enabled: bool,
    /// Session-only pause (`⌥⇧⌘D`, never persisted).
    pub paused_everywhere: bool,
    /// Persisted sites with explicit Dusk preference (`dusk.sites`).
    durable_sites: BTreeMap<String, bool>,
    /// Private-tab in-memory choices (never persisted).
    private_sites: BTreeMap<String, bool>,
}

impl DuskController {
    /// Create a Dusk controller.
    #[must_use]
    pub fn new(enabled: bool) -> Self {
        Self {
            enabled,
            ..Self::default()
        }
    }

    /// Toggle Dusk for `site_host` (`⇧⌘D`, `FEATURES.md` §5.7).
    pub fn toggle_site(&mut self, site_host: &str, currently_active: bool, private: bool) -> bool {
        let site = normalize_site_key(site_host);
        let next = !currently_active;
        if private {
            self.private_sites.insert(site, next);
        } else {
            self.durable_sites.insert(site, next);
        }
        next
    }

    /// Toggle session-wide pause (`⌥⇧⌘D`).
    pub fn toggle_pause_everywhere(&mut self) -> bool {
        self.paused_everywhere = !self.paused_everywhere;
        self.paused_everywhere
    }

    /// Persisted site preferences (`dusk.sites`), excluding private-tab choices.
    #[must_use]
    pub const fn durable_site_preferences(&self) -> &BTreeMap<String, bool> {
        &self.durable_sites
    }

    /// Evaluate Dusk for a page given frame darkness, measured RGB sample,
    /// fullscreen state, stylesheets, and budget (`FEATURES.md` §5.7).
    #[allow(clippy::too_many_arguments)]
    pub fn evaluate_page(
        &self,
        site_host: &str,
        frame_is_dark: bool,
        sample_rgb: (u8, u8, u8),
        fullscreen: bool,
        stylesheets: &[&str],
        budget: &mut DuskBudget,
        private: bool,
    ) -> DuskDecision {
        if !self.enabled || self.paused_everywhere || !frame_is_dark {
            return DuskDecision::Untouched;
        }
        let site = normalize_site_key(site_host);
        let explicit = if private {
            self.private_sites
                .get(&site)
                .or_else(|| self.durable_sites.get(&site))
                .copied()
        } else {
            self.durable_sites.get(&site).copied()
        };

        if explicit == Some(false) {
            return DuskDecision::Untouched;
        }
        let page_is_light = is_measured_light_page(sample_rgb.0, sample_rgb.1, sample_rgb.2);
        if explicit != Some(true) && !page_is_light {
            // A dark site gets no script/observer/sheet at all (`FEATURES.md` §5.7).
            return DuskDecision::Untouched;
        }

        let mut twin_css = String::new();
        for sheet in stylesheets {
            let generated = synthesize_dark_twin_sheet(sheet);
            if !budget.record_sheet(generated.len()) {
                return if fullscreen {
                    DuskDecision::Untouched
                } else {
                    DuskDecision::FilterFallback {
                        css: DUSK_FILTER_FALLBACK_CSS,
                    }
                };
            }
            twin_css.push_str(&generated);
        }
        DuskDecision::DarkTwins { css: twin_css }
    }
}

fn synthesize_dark_twin_sheet(sheet: &str) -> String {
    // Rewrite light ground/text rules using relative OKLCH dark twins without touching images.
    let mut out = sheet
        .replace("#ffffff", "oklch(0.18 0.01 260)")
        .replace("#fff", "oklch(0.18 0.01 260)")
        .replace("white", "oklch(0.18 0.01 260)")
        .replace("#000000", "oklch(0.92 0.01 90)")
        .replace("#000", "oklch(0.92 0.01 90)")
        .replace("black", "oklch(0.92 0.01 90)");
    out.push_str("\nimg, picture, video, canvas { filter: none !important; }\n");
    out
}

